using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace TableStorage.Fluent.SourceGenerators;

/// <summary>
/// Generates the arity-specific FluentTableEntity, FluentPartitionTableEntity and FluentRowTableEntity types,
/// based on the table contexts in the compilation and the <c>GenerateFluentEntities</c> assembly attribute.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class FluentEntityGenerator : IIncrementalGenerator
{
    private const string AttributeFullName = "TableStorage.Fluent.GenerateFluentEntitiesAttribute";
    private const string TableContextAttributeFullName = "TableStorage.TableContextAttribute";
    private const string FluentRuntimeMetadataName = "TableStorage.Fluent.FluentEntityBase";

    private static readonly string[] s_fluentTypeNames = ["FluentTableEntity", "FluentPartitionTableEntity", "FluentRowTableEntity"];

    private const string AttributeSource = """
        // <auto-generated/>
        namespace TableStorage.Fluent
        {
            /// <summary>
            /// Generates the fluent table entities for the given number of generic type parameters.
            /// Arities used by table contexts in this assembly are generated automatically.
            /// </summary>
            [global::Microsoft.CodeAnalysis.EmbeddedAttribute]
            [global::System.AttributeUsage(global::System.AttributeTargets.Assembly, AllowMultiple = true)]
            internal sealed class GenerateFluentEntitiesAttribute : global::System.Attribute
            {
                public GenerateFluentEntitiesAttribute(params int[] arities)
                {
                    Arities = arities;
                }

                /// <summary>
                /// The numbers of generic type parameters to generate.
                /// </summary>
                public int[] Arities { get; }

                /// <summary>
                /// Generate the types as public instead of internal. Public fluent types can conflict with the ones of other assemblies.
                /// </summary>
                public bool Public { get; set; }
            }
        }
        """;

    private static readonly DiagnosticDescriptor s_unsupportedArity = new(
        "TSF001",
        "Unsupported number of fluent types",
        "Fluent entities support between 2 and 16 types, but {0} were requested",
        "TableStorage.Fluent",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor s_duplicateArity = new(
        "TSF002",
        "Duplicate fluent arity",
        "Fluent entities with {0} types are requested more than once",
        "TableStorage.Fluent",
        DiagnosticSeverity.Warning,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static ctx =>
        {
            ctx.AddEmbeddedAttributeDefinition();
            ctx.AddSource("GenerateFluentEntitiesAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8));
        });

        IncrementalValueProvider<ImmutableArray<EquatableArray<ArityRequest>>> fromAttributes = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                AttributeFullName,
                static (node, _) => node is CompilationUnitSyntax,
                static (ctx, ct) => GetAttributeRequests(ctx, ct))
            .Collect();

        IncrementalValueProvider<ImmutableArray<EquatableArray<ArityRequest>>> fromContexts = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                TableContextAttributeFullName,
                static (node, _) => node is ClassDeclarationSyntax,
                static (ctx, ct) => GetContextRequests(ctx, ct))
            .Collect();

        IncrementalValueProvider<CompilationInfo> compilationInfo = context.CompilationProvider
            .Select(static (compilation, ct) => GetCompilationInfo(compilation, ct));

        var combined = fromAttributes.Combine(fromContexts).Combine(compilationInfo);

        context.RegisterSourceOutput(combined, static (spc, source) =>
        {
            ((ImmutableArray<EquatableArray<ArityRequest>> attributes, ImmutableArray<EquatableArray<ArityRequest>> contexts), CompilationInfo info) = source;
            Execute(spc, [.. attributes.SelectMany(x => x), .. contexts.SelectMany(x => x)], info);
        });
    }

    private static EquatableArray<ArityRequest> GetAttributeRequests(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
    {
        var requests = ImmutableArray.CreateBuilder<ArityRequest>();

        foreach (AttributeData attribute in ctx.Attributes)
        {
            ct.ThrowIfCancellationRequested();

            LocationInfo? location = LocationInfo.From(attribute.ApplicationSyntaxReference?.GetSyntax(ct).GetLocation());
            bool isPublic = attribute.NamedArguments.Any(x => x.Key == "Public" && x.Value.Value is true);

            if (attribute.ConstructorArguments.Length is 0 || attribute.ConstructorArguments[0].Kind is not TypedConstantKind.Array)
            {
                continue;
            }

            foreach (TypedConstant value in attribute.ConstructorArguments[0].Values)
            {
                if (value.Value is int arity)
                {
                    requests.Add(new ArityRequest(arity, isPublic, FromAttribute: true, location));
                }
            }
        }

        return new(requests.ToImmutable());
    }

    private static EquatableArray<ArityRequest> GetContextRequests(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol contextSymbol)
        {
            return new([]);
        }

        bool contextIsPublic = IsEffectivelyPublic(contextSymbol);
        var requests = ImmutableArray.CreateBuilder<ArityRequest>();

        foreach (ISymbol member in contextSymbol.GetMembers())
        {
            ct.ThrowIfCancellationRequested();

            if (member is not IPropertySymbol { IsStatic: false } property ||
                property.Type is not INamedTypeSymbol { Name: "TableSet", TypeArguments.Length: 1 } tableSet ||
                tableSet.TypeArguments[0] is not INamedTypeSymbol fluentType ||
                !s_fluentTypeNames.Contains(fluentType.Name))
            {
                continue;
            }

            bool isPublic = contextIsPublic && property.DeclaredAccessibility is Accessibility.Public;
            LocationInfo? location = LocationInfo.From(property.Locations.FirstOrDefault());
            requests.Add(new ArityRequest(fluentType.TypeArguments.Length, isPublic, FromAttribute: false, location));
        }

        return new(requests.ToImmutable());
    }

    private static bool IsEffectivelyPublic(INamedTypeSymbol symbol)
    {
        for (INamedTypeSymbol? current = symbol; current is not null; current = current.ContainingType)
        {
            if (current.DeclaredAccessibility is not Accessibility.Public)
            {
                return false;
            }
        }

        return true;
    }

    private static CompilationInfo GetCompilationInfo(Compilation compilation, CancellationToken ct)
    {
        bool hasRuntime = compilation.GetTypeByMetadataName(FluentRuntimeMetadataName) is not null;
        var provided = ImmutableArray.CreateBuilder<int>();

        if (hasRuntime)
        {
            // Referenced assemblies that expose their fluent types publicly already provide them; generating them again would cause ambiguities.
            foreach (IAssemblySymbol assembly in compilation.SourceModule.ReferencedAssemblySymbols)
            {
                ct.ThrowIfCancellationRequested();

                for (int arity = FluentEmitter.MinArity; arity <= FluentEmitter.MaxArity; arity++)
                {
                    if (!provided.Contains(arity) &&
                        assembly.GetTypeByMetadataName($"TableStorage.Fluent.FluentTableEntity`{arity}") is { DeclaredAccessibility: Accessibility.Public })
                    {
                        provided.Add(arity);
                    }
                }
            }
        }

        return new CompilationInfo(hasRuntime, new(provided.ToImmutable()));
    }

    private static void Execute(SourceProductionContext context, ImmutableArray<ArityRequest> requests, CompilationInfo info)
    {
        if (!info.HasFluentRuntime)
        {
            return;
        }

        HashSet<int> seenInAttributes = [];
        Dictionary<int, bool> arities = [];

        foreach (ArityRequest request in requests)
        {
            if (request.Arity is < FluentEmitter.MinArity or > FluentEmitter.MaxArity)
            {
                context.ReportDiagnostic(Diagnostic.Create(s_unsupportedArity, request.Location?.ToLocation(), request.Arity));
                continue;
            }

            if (request.FromAttribute && !seenInAttributes.Add(request.Arity))
            {
                context.ReportDiagnostic(Diagnostic.Create(s_duplicateArity, request.Location?.ToLocation(), request.Arity));
            }

            arities[request.Arity] = (arities.TryGetValue(request.Arity, out bool isPublic) && isPublic) || request.IsPublic;
        }

        foreach (KeyValuePair<int, bool> arity in arities.OrderBy(x => x.Key))
        {
            if (info.ExternallyProvided.Contains(arity.Key))
            {
                continue;
            }

            context.AddSource($"FluentEntities{arity.Key}.g.cs", SourceText.From(FluentEmitter.Emit(arity.Key, arity.Value), Encoding.UTF8));
        }
    }
}
